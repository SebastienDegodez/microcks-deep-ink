import { useEffect, useId, useRef } from 'react';
import { findCriteriaConflict, validateExampleDraft } from '@/domain/copilot';
import type { Example, Operation } from '@/domain/shared';
import { exampleUrlPath } from '@/domain/catalog';
import { Button, Exchange, ExchangeCard, Icon, Input, Textarea, SectionLabel } from '@microcks/deep-ink';

export type Status = 'pending' | 'accepted' | 'rejected';
export interface Item { example: Example; status: Status; edited: boolean; expanded: boolean; editing: boolean; draftName: string; draftBody: string }

export const fresh = (example: Example, expanded = false): Item => ({
  example, status: 'pending', edited: false, expanded, editing: false, draftName: example.name, draftBody: example.response.body,
});

/** Where the mock serves the operation: `http://microcks.local:8080/rest/API+Pastry/2.0`. */
export interface MockTarget { host: string; basePath: string }

interface ProposalRowProps {
  item: Item;
  op: Operation;
  target: MockTarget;
  served: readonly Example[];
  onPatch: (fn: (i: Item) => Item) => void;
  onAccept: (edited: boolean) => void;
  onReject: () => void;
  onUndo: () => void;
}

/** `path    name = Tartelette Framboise` lines: path parameters first, then the query ones. */
function paramLines(op: Operation, params: Record<string, string>): string {
  const inPath = new Set([...op.path.matchAll(/\{([^}]+)\}/g)].map((m) => m[1]));
  return Object.entries(params).map(([k, v]) => `${(inPath.has(k) ? 'path' : 'query').padEnd(8)}${k} = ${v}`).join('\n');
}

/** One AI proposal: a ghost row (dashed while pending) that opens on its request and response, or on an editor. */
export function ProposalRow({ item, op, target, served, onPatch, onAccept, onReject, onUndo }: ProposalRowProps) {
  const uid = useId();
  const e = item.example;
  // The pressed button unmounts: focus moves to the control that replaces it (WCAG 2.4.3).
  const focusNext = useRef<'undo' | 'accept' | 'name' | 'edit' | undefined>(undefined);
  const undoRef = useRef<HTMLButtonElement>(null);
  const acceptRef = useRef<HTMLButtonElement>(null);
  const editRef = useRef<HTMLButtonElement>(null);
  const nameRef = useRef<HTMLInputElement>(null);
  useEffect(() => {
    const next = focusNext.current;
    if (!next) return;
    focusNext.current = undefined;
    ({ undo: undoRef, accept: acceptRef, edit: editRef, name: nameRef })[next].current?.focus();
  }, [item.status, item.editing]);
  const pending = item.status === 'pending';
  const rejected = item.status === 'rejected';
  const conflict = rejected ? undefined : findCriteriaConflict(e, served);
  const draftError = item.editing ? validateExampleDraft({ name: item.draftName, body: item.draftBody }) : undefined;
  const reqLine = `${op.method} ${target.basePath}${exampleUrlPath(op.path, e.request.params)}`;
  const reqText = `${reqLine} HTTP/1.1\nHost: ${target.host}\nAccept: application/json${e.request.body ? '\nContent-Type: application/json' : ''}`;
  const sub = Object.entries(e.request.params).map(([k, v]) => `${k}=${v}`).join(' · ');
  const open = item.expanded && !item.editing && !rejected;

  return (
    <article aria-label={`${e.name}, ${item.status}`} className="proposal" data-status={item.status}>
      <div className="proposal-head">
        <button type="button" className="proposal-toggle" aria-expanded={item.expanded && !rejected} onClick={() => onPatch((i) => ({ ...i, expanded: !i.expanded }))}>
          <Icon name="chevron" size={14} className="proposal-chevron" />
          <span className="proposal-code">{e.response.status}</span>{' '}
          <span className="proposal-title">
            <span className="proposal-name">{e.name}</span>{' '}
            <span className="proposal-sub">{sub}</span>
          </span>
        </button>

        {pending && !item.editing ? (
          <span className="proposal-state" data-tone="warning"><Icon name="spark" size={13} />Generated by AI, review needed</span>
        ) : null}
        {item.status === 'accepted' ? (
          <span className="proposal-state" data-tone="success">
            <Icon name="check" size={13} />Accepted
            <span className="proposal-ai-tag"><Icon name="spark" size={9} />AI</span>
            {item.edited ? <span className="proposal-edited">edited by MA</span> : null}
          </span>
        ) : null}
        {rejected ? <span className="proposal-state" data-tone="muted"><Icon name="cross" size={13} />Rejected</span> : null}

        <span className="proposal-actions">
          {pending && !item.editing ? (
            <>
              <Button ref={acceptRef} size="sm" variant="primary" onClick={() => { focusNext.current = 'undo'; onAccept(false); }} aria-label={`Accept ${e.name}`}>Accept</Button>
              <Button ref={editRef} size="sm" onClick={() => { focusNext.current = 'name'; onPatch((i) => ({ ...i, editing: true, expanded: true, draftName: i.example.name, draftBody: i.example.response.body })); }} aria-label={`Edit ${e.name}`}>Edit</Button>
              <Button size="sm" variant="link" onClick={() => { focusNext.current = 'undo'; onReject(); }} aria-label={`Reject ${e.name}`}>Reject</Button>
            </>
          ) : null}
          {!pending ? <Button ref={undoRef} size="sm" variant="link" onClick={() => { focusNext.current = 'accept'; onUndo(); }} aria-label={`Undo for ${e.name}`}>Undo</Button> : null}
        </span>
      </div>

      {conflict ? (
        <p className="proposal-conflict" role="note"><Icon name="warning" size={13} />{conflict}</p>
      ) : null}

      {open ? (
        <Exchange separator={false} className="proposal-body">
          <ExchangeCard
            size="sm"
            headingLevel={3}
            title="Request"
            label={`Request of ${e.name}`}
            blocks={[
              { label: 'Request line and headers', text: reqText, tone: 'secondary' },
              { label: 'Parameters', text: paramLines(op, e.request.params), tone: 'params' },
              ...(e.request.body ? [{ label: 'Request body', text: e.request.body }] : []),
            ]}
          />
          <ExchangeCard
            size="sm"
            headingLevel={3}
            title="Response"
            label={`Response of ${e.name}`}
            status={`${e.response.status} · application/json`}
            blocks={[{ label: 'Response body', text: e.response.body, grow: true }]}
          />
        </Exchange>
      ) : null}

      {item.editing ? (
        <div className="proposal-edit proposal-body">
          <div className="proposal-edit-row">
            <div className="proposal-edit-field" data-size="name">
              <SectionLabel as="label" lineHeight="normal" htmlFor={`${uid}-name`}>Example name</SectionLabel>
              <Input ref={nameRef} id={`${uid}-name`} value={item.draftName} onChange={(ev) => onPatch((i) => ({ ...i, draftName: ev.target.value }))} />
            </div>
            <div className="proposal-edit-field" data-size="request">
              <SectionLabel lineHeight="normal" id={`${uid}-req`}>Request</SectionLabel>
              <span className="proposal-edit-request" aria-labelledby={`${uid}-req`} role="group">{reqLine}</span>
            </div>
          </div>
          <div className="proposal-edit-field">
            <SectionLabel as="label" lineHeight="normal" htmlFor={`${uid}-body`}>Response body · application/json</SectionLabel>
            <Textarea
              id={`${uid}-body`}
              mono
              spellCheck={false}
              rows={Math.min(18, item.draftBody.split('\n').length + 1)}
              value={item.draftBody}
              aria-invalid={draftError ? true : undefined}
              aria-describedby={draftError ? `${uid}-err` : undefined}
              onChange={(ev) => onPatch((i) => ({ ...i, draftBody: ev.target.value }))}
            />
            {draftError ? <span id={`${uid}-err`} className="proposal-edit-error"><Icon name="cross" size={13} />{draftError}</span> : null}
          </div>
          <div className="proposal-edit-actions">
            <Button size="sm" variant="primary" disabled={Boolean(draftError)} onClick={() => { focusNext.current = 'undo'; onAccept(true); }}>Apply and accept</Button>
            <Button size="sm" onClick={() => { focusNext.current = 'edit'; onPatch((i) => ({ ...i, editing: false, draftName: i.example.name, draftBody: i.example.response.body })); }}>Cancel edit</Button>
          </div>
        </div>
      ) : null}
    </article>
  );
}
