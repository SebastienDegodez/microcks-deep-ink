<script lang="ts">
  import { findCriteriaConflict, validateExampleDraft } from '@microcks/demo-core/domain/copilot';
  import type { Example, Operation } from '@microcks/demo-core/domain/shared';
  import { Button, Exchange, ExchangeCard, Icon, Input, SectionLabel, Textarea } from '@microcks/deep-ink';
  import { paramLines, proposalSub, requestLine, requestText, type Item, type MockTarget } from './proposal';

  /** One AI proposal: a ghost row (dashed while pending) that opens on its request and response, or on an editor. */
  interface Props {
    item: Item;
    op: Operation;
    target: MockTarget;
    served: readonly Example[];
    onpatch: (fn: (i: Item) => Item) => void;
    onaccept: (edited: boolean) => void;
    onreject: () => void;
    onundo: () => void;
  }

  let { item, op, target, served, onpatch, onaccept, onreject, onundo }: Props = $props();
  const uid = $props.id();

  // The pressed button unmounts: focus moves to the control that replaces it (WCAG 2.4.3).
  let focusNext: 'undo' | 'accept' | 'name' | 'edit' | undefined;
  let undoEl = $state<HTMLButtonElement | undefined>();
  let acceptEl = $state<HTMLButtonElement | undefined>();
  let editEl = $state<HTMLButtonElement | undefined>();
  let nameEl = $state<HTMLInputElement | undefined>();
  $effect(() => {
    void item.status;
    void item.editing;
    // Every control is read, so the effect runs again when one is bound: the replacing control may not be bound
    // yet, or its variable may still hold the removed one.
    const controls = { undo: undoEl, accept: acceptEl, edit: editEl, name: nameEl };
    const el = focusNext && controls[focusNext];
    if (!el?.isConnected) return;
    focusNext = undefined;
    el.focus();
  });

  const e = $derived(item.example);
  const pending = $derived(item.status === 'pending');
  const rejected = $derived(item.status === 'rejected');
  const conflict = $derived(rejected ? undefined : findCriteriaConflict(e, served));
  const draftError = $derived(item.editing ? validateExampleDraft({ name: item.draftName, body: item.draftBody }) : undefined);
  const reqLine = $derived(requestLine(op, target, e));
  const reqText = $derived(requestText(reqLine, target, e));
  const sub = $derived(proposalSub(e));
  const open = $derived(item.expanded && !item.editing && !rejected);
</script>

{#snippet request()}<ExchangeCard
    size="sm"
    headingLevel={3}
    title="Request"
    label={`Request of ${e.name}`}
    blocks={[
      { label: 'Request line and headers', text: reqText, tone: 'secondary' },
      { label: 'Parameters', text: paramLines(op, e.request.params), tone: 'params' },
      ...(e.request.body ? [{ label: 'Request body', text: e.request.body }] : []),
    ]}
  />{/snippet}
{#snippet response()}<ExchangeCard
    size="sm"
    headingLevel={3}
    title="Response"
    label={`Response of ${e.name}`}
    status={`${e.response.status} · application/json`}
    blocks={[{ label: 'Response body', text: e.response.body, grow: true }]}
  />{/snippet}

<article aria-label={`${e.name}, ${item.status}`} class="proposal" data-status={item.status}
  ><div class="proposal-head"
    ><button type="button" class="proposal-toggle" aria-expanded={item.expanded && !rejected} onclick={() => onpatch((i) => ({ ...i, expanded: !i.expanded }))}
      ><Icon name="chevron" size={14} class="proposal-chevron" /><span class="proposal-code">{e.response.status}</span>{' '}<span class="proposal-title"
        ><span class="proposal-name">{e.name}</span>{' '}<span class="proposal-sub">{sub}</span></span
      ></button
    >{#if pending && !item.editing}<span class="proposal-state" data-tone="warning"><Icon name="spark" size={13} />Generated by AI, review needed</span>{/if}{#if item.status === 'accepted'}<span
        class="proposal-state"
        data-tone="success"
        ><Icon name="check" size={13} />Accepted<span class="proposal-ai-tag"><Icon name="spark" size={9} />AI</span>{#if item.edited}<span class="proposal-edited"
            >edited by MA</span
          >{/if}</span
      >{/if}{#if rejected}<span class="proposal-state" data-tone="muted"><Icon name="cross" size={13} />Rejected</span>{/if}<span class="proposal-actions"
      >{#if pending && !item.editing}<Button
          bind:element={acceptEl}
          size="sm"
          variant="primary"
          onclick={() => {
            focusNext = 'undo';
            onaccept(false);
          }}
          aria-label={`Accept ${e.name}`}>Accept</Button
        ><Button
          bind:element={editEl}
          size="sm"
          onclick={() => {
            focusNext = 'name';
            onpatch((i) => ({ ...i, editing: true, expanded: true, draftName: i.example.name, draftBody: i.example.response.body }));
          }}
          aria-label={`Edit ${e.name}`}>Edit</Button
        ><Button
          size="sm"
          variant="link"
          onclick={() => {
            focusNext = 'undo';
            onreject();
          }}
          aria-label={`Reject ${e.name}`}>Reject</Button
        >{/if}{#if !pending}<Button
          bind:element={undoEl}
          size="sm"
          variant="link"
          onclick={() => {
            focusNext = 'accept';
            onundo();
          }}
          aria-label={`Undo for ${e.name}`}>Undo</Button
        >{/if}</span
    ></div
  >{#if conflict}<p class="proposal-conflict" role="note"><Icon name="warning" size={13} class="proposal-conflict-icon" />{conflict}</p>{/if}{#if open}<Exchange
      separator={false}
      class="proposal-body"
      children={[request, response]}
    />{/if}{#if item.editing}<div class="proposal-edit proposal-body"
      ><div class="proposal-edit-row"
        ><div class="proposal-edit-field" data-size="name"
          ><SectionLabel as="label" lineHeight="normal" htmlFor={`${uid}-name`}>Example name</SectionLabel
          ><Input
            bind:element={nameEl}
            id={`${uid}-name`}
            value={item.draftName}
            oninput={(ev) => {
              const draftName = ev.currentTarget.value;
              onpatch((i) => ({ ...i, draftName }));
            }}
          /></div
        ><div class="proposal-edit-field" data-size="request"
          ><SectionLabel lineHeight="normal" id={`${uid}-req`}>Request</SectionLabel
          ><span class="proposal-edit-request" aria-labelledby={`${uid}-req`} role="group">{reqLine}</span></div
        ></div
      ><div class="proposal-edit-field"
        ><SectionLabel as="label" lineHeight="normal" htmlFor={`${uid}-body`}>Response body · application/json</SectionLabel
        ><Textarea
          id={`${uid}-body`}
          mono
          spellcheck={false}
          rows={Math.min(18, item.draftBody.split('\n').length + 1)}
          value={item.draftBody}
          aria-invalid={draftError ? true : undefined}
          aria-describedby={draftError ? `${uid}-err` : undefined}
          oninput={(ev) => {
            const draftBody = ev.currentTarget.value;
            onpatch((i) => ({ ...i, draftBody }));
          }}
        />{#if draftError}<span id={`${uid}-err`} class="proposal-edit-error"><Icon name="cross" size={13} />{draftError}</span>{/if}</div
      ><div class="proposal-edit-actions"
        ><Button
          size="sm"
          variant="primary"
          disabled={Boolean(draftError)}
          onclick={() => {
            focusNext = 'undo';
            onaccept(true);
          }}>Apply and accept</Button
        ><Button
          size="sm"
          onclick={() => {
            focusNext = 'edit';
            onpatch((i) => ({ ...i, editing: false, draftName: i.example.name, draftBody: i.example.response.body }));
          }}>Cancel edit</Button
        ></div
      ></div
    >{/if}</article
>
