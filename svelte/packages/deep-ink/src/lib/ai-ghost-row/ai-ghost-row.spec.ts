import { fireEvent, render, screen } from '@testing-library/svelte';
import { createRawSnippet } from 'svelte';
import { describe, expect, it, vi } from 'vitest';
import AiGhostRow from './AiGhostRow.svelte';
const html = (s: string) => createRawSnippet(() => ({ render: () => s }));
describe('AiGhostRow', () => {
  it('is a labelled group with named action buttons and unconfirmed text', async () => {
    const handlers = { onaccept: vi.fn(), onedit: vi.fn(), onreject: vi.fn() };
    render(AiGhostRow, { props: { name: 'Tartelette Framboise', ...handlers, children: html('Tartelette Framboise · 200') } });
    expect(screen.getByRole('group', { name: 'AI suggestion: Tartelette Framboise' })).toBeTruthy();
    expect(screen.getByText('Generated by AI, review needed')).toBeTruthy();
    await fireEvent.click(screen.getByRole('button', { name: /Accept\s+Tartelette Framboise/ }));
    await fireEvent.click(screen.getByRole('button', { name: /Edit\s+Tartelette Framboise/ }));
    await fireEvent.click(screen.getByRole('button', { name: /Reject\s+Tartelette Framboise/ }));
    expect(handlers.onaccept).toHaveBeenCalledOnce(); expect(handlers.onedit).toHaveBeenCalledOnce(); expect(handlers.onreject).toHaveBeenCalledOnce();
  });
  it('sets busy state and disables all actions', () => {
    render(AiGhostRow, { props: { name: 'Example', busy: true, onaccept: vi.fn(), onedit: vi.fn(), onreject: vi.fn() } });
    expect(screen.getByRole('group').getAttribute('aria-busy')).toBe('true');
    expect(screen.getAllByRole('button').every((b) => (b as HTMLButtonElement).disabled)).toBe(true);
  });
});
