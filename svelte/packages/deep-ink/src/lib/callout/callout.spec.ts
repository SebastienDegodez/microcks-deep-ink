import { render, screen } from '@testing-library/svelte';
import { createRawSnippet } from 'svelte';
import { describe, expect, it } from 'vitest';
import { axeViolations } from '../../../test/axe';
import Callout from './Callout.svelte';

const html = (h: string) => createRawSnippet(() => ({ render: () => h }));

describe('Callout outline', () => {
  it('is a note with a named icon, the outline variant and the small size', async () => {
    render(Callout, { props: { tone: 'warning', variant: 'outline', children: html('<span>Install the main package first.</span>') } });
    render(Callout, { props: { tone: 'warning', variant: 'outline', size: 'sm', live: 'polite', children: html('<span>Masked token.</span>') } });
    const note = screen.getByRole('note');
    expect(note.getAttribute('data-variant')).toBe('outline');
    expect(screen.getAllByRole('img', { name: 'Warning' })).toHaveLength(2);
    const status = screen.getByRole('status');
    expect(status.getAttribute('data-size')).toBe('sm');
    expect(await axeViolations(document.body)).toEqual([]);
  });

  it('AI outline note: dashed frame, no default title when the text says it, the icon names the tone', async () => {
    const { container } = render(Callout, { props: { tone: 'ai', variant: 'outline', title: '', children: html("<span>Proposed by AI from the contract's Pastry schema.</span>") } });
    const note = screen.getByRole('note');
    expect(note.getAttribute('data-tone')).toBe('ai');
    expect(note.querySelector('.callout-title')).toBeNull();
    expect(screen.getByRole('img', { name: 'AI suggestion' })).toBeTruthy();
    expect(await axeViolations(container)).toEqual([]);
  });
});

describe('Callout', () => {
  it('is an alert labelled by its title when assertive, with a decorative icon and snippet actions', async () => {
    const { container } = render(Callout, {
      props: { tone: 'danger', title: 'Import failed', live: 'assertive', actions: html('<button type="button">Retry</button>'), children: html('<span>Not OpenAPI.</span>') },
    });
    const alert = screen.getByRole('alert', { name: 'Import failed' });
    expect(alert.querySelector('svg')!.getAttribute('aria-hidden')).toBe('true');
    expect(screen.getByRole('button', { name: 'Retry' }).parentElement!.className).toBe('callout-actions');
    expect(await axeViolations(container)).toEqual([]);
  });

  it('has no live role by default, and the ai tone gets its default title', () => {
    const { container } = render(Callout, { props: { tone: 'ai', children: html('<span>3 examples.</span>') } });
    expect(container.querySelector('.callout')!.hasAttribute('role')).toBe(false);
    expect(container.querySelector('.callout-title')!.textContent).toBe('Generated by AI, review needed');
  });
});
