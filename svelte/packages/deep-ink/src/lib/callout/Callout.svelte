
<script lang="ts" module>
  export type CalloutTone = 'info' | 'success' | 'warning' | 'danger' | 'ai';

  const ICON = { info: 'info', success: 'check', warning: 'warning', danger: 'cross', ai: 'spark' } as const;
  const TONE_WORD = { info: 'Information', success: 'Success', warning: 'Warning', danger: 'Error', ai: 'AI suggestion' } as const;
  const AI_TITLE = 'Generated by AI, review needed';
</script>

<script lang="ts">
  import type { Snippet } from 'svelte';
  import type { HTMLAttributes } from 'svelte/elements';
  import Icon from '../icon/Icon.svelte';
  import { eventProps, type NativeHandlers } from '../event-props';

  type Props = Omit<HTMLAttributes<HTMLDivElement>, 'class' | 'title' | 'children'> &
    NativeHandlers<HTMLDivElement> & {
    tone?: CalloutTone;
    /** An empty string renders no title, even for the ai tone. */
    title?: string | Snippet;
    /** polite renders role="status", assertive renders role="alert", false renders no live role. */
    live?: 'polite' | 'assertive' | false;
    actions?: string | Snippet;
    /** `outline`: a thin tone-coloured frame, no fill, 14px icon; a `role="note"` by default. */
    variant?: 'filled' | 'outline';
    /** `sm` (outline): 12px text, padding 9px 11px. */
    size?: 'md' | 'sm';
    class?: string;
    children?: Snippet;
  };

  let { tone = 'info', title, live = false, actions, variant = 'filled', size = 'md', class: cssClass, role, children, ...rest }: Props = $props();

  const titleId = $props.id();
  const heading = $derived(title ?? (tone === 'ai' ? AI_TITLE : undefined));
  const liveRole = $derived(live === 'assertive' ? 'alert' : live === 'polite' ? 'status' : undefined);
</script>

{#snippet node(content: string | Snippet)}{#if typeof content === 'function'}{@render content()}{:else}{content}{/if}{/snippet}

<div
  {...eventProps(rest)}
  class={['callout', cssClass].filter(Boolean).join(' ')}
  data-tone={tone}
  data-variant={variant === 'outline' ? 'outline' : undefined}
  data-size={size === 'sm' ? 'sm' : undefined}
  role={liveRole ?? role ?? (variant === 'outline' ? 'note' : undefined)}
  aria-labelledby={heading ? titleId : rest['aria-labelledby']}
  ><Icon name={ICON[tone]} size={18} label={heading ? undefined : TONE_WORD[tone]} /><div class="callout-body"
    >{#if heading}<p class="callout-title" id={titleId}>{@render node(heading)}</p>{/if}{#if children}<div
        class="callout-content">{@render children()}</div
      >{/if}{#if actions}<div class="callout-actions">{@render node(actions)}</div>{/if}</div
  ></div
>
