#!/usr/bin/env node
// Builds the whole Deep Ink stylesheet in one file, for packages that ship it (React, later Svelte).
//
//   node scripts/build-css.mjs
//
// Writes dist/deep-ink.css and dist/deep-ink.no-fonts.css: the layer order first, then the tokens (unlayered, on
// :root), then base and every item in its layer, in the order of css-order.json (the order the demo has always
// loaded them in, so the cascade inside @layer deep-ink.components does not change). Items missing from that list
// follow, dependencies first. Zero dependencies; only writes inside packages/registry/dist.
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const PKG_ROOT = resolve(HERE, '..');
const TOKENS_DIST = resolve(PKG_ROOT, '..', 'tokens', 'dist');

export const LAYER_ORDER = '@layer deep-ink.base, deep-ink.components;';

const readJson = (path) => JSON.parse(readFileSync(path, 'utf8'));

/** Item names in stylesheet order: css-order.json first, then the rest, each after its dependencies (alphabetical ties). */
export function cssOrder({ root = PKG_ROOT } = {}) {
  const itemsDir = join(root, 'items');
  const items = new Map(
    readdirSync(itemsDir)
      .filter((f) => f.endsWith('.json'))
      .sort()
      .map((f) => readJson(join(itemsDir, f)))
      .map((m) => [m.name, m]),
  );
  const listed = existsSync(join(root, 'css-order.json')) ? readJson(join(root, 'css-order.json')) : [];
  const order = [];
  const seen = new Set();
  const visit = (name) => {
    if (seen.has(name) || !items.has(name)) return;
    seen.add(name);
    for (const dep of [...items.get(name).registryDependencies].sort()) visit(dep);
    order.push(name);
  };
  for (const n of [...listed, ...[...items.keys()].sort()]) visit(n);
  return order.filter((n) => n !== 'tokens' && existsSync(join(root, 'src', 'css', `${n}.css`)));
}

/**
 * @param {{ root?: string, tokensDist?: string, write?: boolean }} [options]
 * @returns {{ css: string, cssNoFonts: string, order: string[] }}
 */
export function buildCss({ root = PKG_ROOT, tokensDist = TOKENS_DIST, write = true } = {}) {
  const tokens = join(tokensDist, 'deep-ink.css');
  const tokensNoFonts = join(tokensDist, 'deep-ink.no-fonts.css');
  if (!existsSync(tokens) || !existsSync(tokensNoFonts)) {
    throw new Error('packages/tokens/dist is missing (run `pnpm --filter @microcks-deep-ink/tokens build`)');
  }
  const order = cssOrder({ root });
  const body = order.map((n) => `/* ── ${n} ── */\n${readFileSync(join(root, 'src', 'css', `${n}.css`), 'utf8')}`).join('\n');
  const head = '/* Deep Ink: tokens, base and every component, layered. Generated by packages/registry/scripts/build-css.mjs. */\n';
  // The layer statement may precede the tokens' font @import; nothing else may.
  const assemble = (tokensCss) => `${LAYER_ORDER}\n${head}/* ── tokens ── */\n${tokensCss}\n${body}`;
  const css = assemble(readFileSync(tokens, 'utf8'));
  const cssNoFonts = assemble(readFileSync(tokensNoFonts, 'utf8'));
  if (write) {
    const dist = join(root, 'dist');
    mkdirSync(dist, { recursive: true });
    writeFileSync(join(dist, 'deep-ink.css'), css);
    writeFileSync(join(dist, 'deep-ink.no-fonts.css'), cssNoFonts);
  }
  return { css, cssNoFonts, order };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    const { order } = buildCss();
    console.log(`css: tokens + ${order.length} stylesheets -> dist/deep-ink.css, deep-ink.no-fonts.css`);
  } catch (e) {
    console.error(`error: ${e.message}`);
    process.exit(1);
  }
}
