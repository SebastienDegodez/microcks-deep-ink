import { ChangeDetectionStrategy, Component, contentChild, Directive, input } from '@angular/core';
import { IconComponent } from './icon';
import type { IconName } from './icon';

export type CalloutTone = 'info' | 'success' | 'warning' | 'danger' | 'ai';

const ICON: Record<CalloutTone, IconName> = { info: 'info', success: 'check', warning: 'warning', danger: 'cross', ai: 'spark' };
const TONE_WORD: Record<CalloutTone, string> = { info: 'Information', success: 'Success', warning: 'Warning', danger: 'Error', ai: 'AI suggestion' };
const AI_TITLE = 'Generated by AI, review needed';

let nextId = 0;

/** Buttons or links under the callout text: `<div mkCalloutActions>…</div>`. */
@Directive({ selector: '[mkCalloutActions]' })
export class CalloutActionsDirective {}

/**
 * Tone-colored message block. `live` renders `role="status"` (polite) or `role="alert"` (assertive).
 * Without a title the icon carries the tone word; with one, the title does.
 */
@Component({
  selector: 'mk-callout',
  changeDetection: ChangeDetectionStrategy.OnPush,
  imports: [IconComponent],
  host: {
    class: 'callout',
    '[attr.data-tone]': 'tone()',
    '[attr.data-variant]': "variant() === 'outline' ? 'outline' : null",
    '[attr.data-size]': "size() === 'sm' ? 'sm' : null",
    '[attr.role]': 'role()',
    '[attr.aria-labelledby]': 'heading() ? titleId : null',
    // `title` is an input here: do not leave it on the element as a tooltip.
    '[attr.title]': 'null',
  },
  template: `
    <svg mkIcon [name]="icon()" [size]="18" [label]="heading() ? undefined : toneWord()"></svg>
    <div class="callout-body">
      @if (heading()) {
        <p class="callout-title" [id]="titleId">{{ heading() }}</p>
      }
      <div class="callout-content"><ng-content /></div>
      @if (actions()) {
        <div class="callout-actions"><ng-content select="[mkCalloutActions]" /></div>
      }
    </div>
  `,
})
export class CalloutComponent {
  readonly tone = input<CalloutTone>('info');
  readonly title = input<string>();
  /** polite renders role="status", assertive renders role="alert", false renders no live role. */
  readonly live = input<'polite' | 'assertive' | false>(false);
  /** `outline`: a thin tone-coloured frame, no fill, tone-coloured 13px text, 14px icon; a `role="note"` by default. */
  readonly variant = input<'filled' | 'outline'>('filled');
  /** `sm` (outline): 12px text, padding 9px 11px. */
  readonly size = input<'md' | 'sm'>('md');

  protected readonly actions = contentChild(CalloutActionsDirective);
  protected readonly titleId = `mk-callout-title-${++nextId}`;

  protected heading(): string | undefined {
    return this.title() ?? (this.tone() === 'ai' ? AI_TITLE : undefined);
  }
  protected icon(): IconName {
    return ICON[this.tone()];
  }
  protected toneWord(): string {
    return TONE_WORD[this.tone()];
  }
  protected role(): string | null {
    const live = this.live();
    return live === 'assertive' ? 'alert' : live === 'polite' ? 'status' : this.variant() === 'outline' ? 'note' : null;
  }
}
