// @vitest-environment jsdom
import { afterEach, describe, expect, it, vi } from 'vitest';
import { cleanup, fireEvent, render, screen } from '@testing-library/react';
import { AiGhostRow } from './ai-ghost-row';

afterEach(cleanup);

// Whitespace between the visible word and the hidden suffix is normalised by browsers; match loosely.
const btn = (verb: string) => screen.getByRole('button', { name: new RegExp(`^${verb}\\s+Tartelette Framboise$`) });

const setup = (busy = false) => {
  const handlers = { onAccept: vi.fn(), onEdit: vi.fn(), onReject: vi.fn() };
  render(
    <AiGhostRow name="Tartelette Framboise" busy={busy} {...handlers}>
      Tartelette Framboise · 200
    </AiGhostRow>,
  );
  return handlers;
};

describe('AiGhostRow', () => {
  it('is a labelled group', () => {
    setup();
    expect(screen.getByRole('group', { name: 'AI suggestion: Tartelette Framboise' })).toBeTruthy();
  });

  it('names every button with the item name', () => {
    setup();
    for (const verb of ['Accept', 'Edit', 'Reject']) {
      expect(btn(verb)).toBeTruthy();
    }
  });

  it('runs the matching handler', () => {
    const h = setup();
    fireEvent.click(btn('Accept'));
    fireEvent.click(btn('Edit'));
    fireEvent.click(btn('Reject'));
    expect(h.onAccept).toHaveBeenCalledTimes(1);
    expect(h.onEdit).toHaveBeenCalledTimes(1);
    expect(h.onReject).toHaveBeenCalledTimes(1);
  });

  it('states that the row is unconfirmed in text', () => {
    setup();
    expect(screen.getByText('Generated by AI, review needed')).toBeTruthy();
  });

  it('disables the actions and sets aria-busy while busy', () => {
    setup(true);
    expect(screen.getByRole('group').getAttribute('aria-busy')).toBe('true');
    for (const b of screen.getAllByRole('button')) expect((b as HTMLButtonElement).disabled).toBe(true);
  });
});
