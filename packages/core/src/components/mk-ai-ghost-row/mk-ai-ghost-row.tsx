import { Component, Event, EventEmitter, Host, Prop, h } from '@stencil/core';
import { icon } from '../../utils/icons';

/**
 * An AI-generated example, inline and visibly unconfirmed until a human acts on it.
 * @slot - Example summary, e.g. "Tartelette Framboise · 200".
 */
@Component({
  tag: 'mk-ai-ghost-row',
  shadow: true,
  styles: `
    :host { display: block; }
    .g { border: 1.5px dashed var(--warning); border-radius: var(--radius-panel); padding: var(--space-3) var(--space-4); display: flex; flex-wrap: wrap; gap: var(--space-3); align-items: center; color: var(--text); }
    .l { display: inline-flex; gap: 6px; align-items: center; font: 600 12px/16px var(--font-ui); color: var(--warning); }
    .n { font: var(--type-code); }
    .a { margin-left: auto; display: flex; gap: var(--space-2); }
  `,
})
export class MkAiGhostRow {
  @Prop() label = 'Generated by AI, review needed';

  @Event() mkAccept!: EventEmitter<void>;
  @Event() mkEdit!: EventEmitter<void>;
  @Event() mkReject!: EventEmitter<void>;

  render() {
    return (
      <Host role="group" aria-label={this.label}>
        <div class="g">
          <span class="l">
            {icon('spark', 14)}
            {this.label}
          </span>
          <span class="n">
            <slot />
          </span>
          <span class="a">
            <mk-button variant="primary" size="sm" onMkClick={() => this.mkAccept.emit()}>Accept</mk-button>
            <mk-button variant="secondary" size="sm" onMkClick={() => this.mkEdit.emit()}>Edit</mk-button>
            <mk-button variant="ghost" size="sm" onMkClick={() => this.mkReject.emit()}>Reject</mk-button>
          </span>
        </div>
      </Host>
    );
  }
}
