import { useId, type HTMLAttributes, type ReactNode } from 'react';
import { Icon } from './icon';

export type CalloutTone = 'info' | 'success' | 'warning' | 'danger' | 'ai';

export interface CalloutProps extends Omit<HTMLAttributes<HTMLDivElement>, 'title'> {
  tone?: CalloutTone;
  title?: ReactNode;
  /** polite renders role="status", assertive renders role="alert", false renders no live role. */
  live?: 'polite' | 'assertive' | false;
  actions?: ReactNode;
  /** `outline`: a thin tone-coloured frame, no fill, tone-coloured 13px text, 14px icon; a `role="note"` by default (Behavior, Hub, Sources, TestCreate). */
  variant?: 'filled' | 'outline';
  /** `sm` (outline): 12px text, padding 9px 11px (TestCreate aside). */
  size?: 'md' | 'sm';
}

const ICON = { info: 'info', success: 'check', warning: 'warning', danger: 'cross', ai: 'spark' } as const;
const TONE_WORD = { info: 'Information', success: 'Success', warning: 'Warning', danger: 'Error', ai: 'AI suggestion' } as const;
const AI_TITLE = 'Generated by AI, review needed';

export function Callout({ tone = 'info', title, live = false, actions, variant = 'filled', size = 'md', className, children, ...rest }: CalloutProps) {
  const titleId = useId();
  const heading = title ?? (tone === 'ai' ? AI_TITLE : undefined);
  const role = live === 'assertive' ? 'alert' : live === 'polite' ? 'status' : undefined;
  return (
    <div
      {...rest}
      className={['callout', className].filter(Boolean).join(' ')}
      data-tone={tone}
      data-variant={variant === 'outline' ? 'outline' : undefined}
      data-size={size === 'sm' ? 'sm' : undefined}
      role={role ?? rest.role ?? (variant === 'outline' ? 'note' : undefined)}
      aria-labelledby={heading ? titleId : rest['aria-labelledby']}
    >
      {/* Without a title the icon carries the tone word; with one, the title does. */}
      <Icon name={ICON[tone]} size={18} label={heading ? undefined : TONE_WORD[tone]} />
      <div className="callout-body">
        {heading ? (
          <p className="callout-title" id={titleId}>
            {heading}
          </p>
        ) : null}
        {children ? <div className="callout-content">{children}</div> : null}
        {actions ? <div className="callout-actions">{actions}</div> : null}
      </div>
    </div>
  );
}
